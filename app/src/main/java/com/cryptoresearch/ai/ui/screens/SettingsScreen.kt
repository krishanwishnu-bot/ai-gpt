private const val PRIVACY = """Crypto Research AI does not collect, transmit or sell personal information. There are no accounts, no analytics and no advertising.

Stored only on your device: your watchlist, saved research reports, cached market data, the virtual (simulated) portfolio, your settings, and — if you enter one — an optional CoinGecko API key, kept in Android's encrypted storage.

Network requests are made over HTTPS directly from your device to public data providers (CoinGecko, CoinLore, Binance public market data, CryptoCompare, alternative.me). These providers can see your IP address as with any web request, according to their own privacy policies. No wallet, exchange or personal data is ever sent.

The app cannot trade, connect to exchanges or move real money. You can delete saved reports and cached data at any time in Settings → Storage."""

private const val SOURCES = """Market data & rankings: CoinGecko public API (primary), CoinLore (fallback).
Historical OHLCV candles: Binance public market-data endpoint (spot, USDT pairs); fallback: price series from CoinGecko, which has no per-candle volume (marked approximate).
News: CryptoCompare news API (headlines, short snippets and links only).
Sentiment: keyword heuristic on news text + alternative.me Fear & Greed Index (market-wide).

Limitations: free public APIs may rate-limit or change; data can be delayed or unavailable and is then marked cached/stale. Volume delta, volume profile, Fair Value Gaps, Order Blocks and Elliott waves are approximations from public candle data; no order-book, liquidation or institutional-flow data is used. Social-media sentiment is not included. No AI language model runs in this version; reports are generated by rule-based calculation modules."""

@Composable
fun SettingsScreen(vm: AppViewModel) {
    val s by vm.settings.collectAsState()
    val storage by vm.storageInfo.collectAsState()
    val ctx = LocalContext.current
    var keyText by rememberSaveable { mutableStateOf("") }
    var showPrivacy by rememberSaveable { mutableStateOf(false) }
    var showSources by rememberSaveable { mutableStateOf(false) }
    var showAbout by rememberSaveable { mutableStateOf(false) }
    var notifPermAsked by remember { mutableStateOf(false) }

    LaunchedEffect(Unit) { vm.refreshStorageInfo() }

    val permLauncher = rememberLauncherForActivityResult(ActivityResultContracts.RequestPermission()) { granted ->
        notifPermAsked = true
        if (!granted) vm.message.value = "Notification permission denied. Enable it in Android settings to receive notifications."
    }

    fun ensurePermission() {
        if (Build.VERSION.SDK_INT >= 33 && !Notifier.hasPermission(ctx)) {
            permLauncher.launch(android.Manifest.permission.POST_NOTIFICATIONS)
        }
    }

    @Composable
    fun SwitchRow(label: String, desc: String, checked: Boolean, onChange: (Boolean) -> Unit) {
        Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
            androidx.compose.foundation.layout.Column(Modifier.weight(1f)) {
                Text(label, style = MaterialTheme.typography.bodyMedium)
                Muted(desc)
            }
            Switch(checked = checked, onCheckedChange = onChange)
        }
    }

    LazyColumn(
        Modifier.fillMaxWidth(),
        contentPadding = androidx.compose.foundation.layout.PaddingValues(12.dp),
        verticalArrangement = Arrangement.spacedBy(10.dp)
    ) {
        item {
            Panel {
                SectionTitle("Theme")
                ChoiceRow(listOf("navy", "black", "light", "system"), s.theme, { it.replaceFirstChar { c -> c.uppercase() } }, { v -> vm.updateSettings { it.copy(theme = v) } })
            }
        }
        item {
            Panel {
                SectionTitle("Data sources")
                SwitchRow("Allow fallback providers", "Use CoinLore / CoinGecko-derived data when the primary source fails. Fallback data is clearly labelled.", s.allowFallback) { v ->
                    vm.updateSettings { it.copy(allowFallback = v) }
                }
                Muted("Primary: CoinGecko (market) + Binance public data (candles) · News: CryptoCompare")
            }
        }
        item {
            Panel {
                SectionTitle("API configuration")
                Muted("No key is required. An optional free CoinGecko Demo API key can raise rate limits. It is stored encrypted on this device and never included in the app's code.")
                if (!vm.settingsStore.secureStorageAvailable()) Muted("Secure storage is unavailable on this device, so keys cannot be saved.")
                OutlinedTextField(
                    value = keyText, onValueChange = { keyText = it }, singleLine = true, label = { Text("CoinGecko API key (optional)") },
                    visualTransformation = PasswordVisualTransformation(), modifier = Modifier.fillMaxWidth()
                )
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    Button(onClick = { vm.saveApiKey(keyText); keyText = "" }, enabled = keyText.isNotBlank(), modifier = Modifier.weight(1f)) { Text("Save key") }
                    OutlinedButton(onClick = { vm.saveApiKey(""); keyText = "" }, modifier = Modifier.weight(1f)) { Text("Remove key") }
                }
                Muted(if (vm.settingsStore.apiKey().isNullOrBlank()) "No key saved." else "A key is saved.")
            }
        }
        item {
            Panel {
                SectionTitle("Refresh interval")
                ChoiceRow(listOf(0, 5, 15, 30, 60), s.refreshMinutes, { if (it == 0) "Manual" else "${it}m" }, { v -> vm.updateSettings { it.copy(refreshMinutes = v) } })
                Muted("Automatic refresh runs only while the app is open. Background checks (for notifications only) run at most every 15 minutes, and only if a notification type below is enabled.")
            }
        }
        item {
            Panel {
                SectionTitle("Analysis preferences")
                Muted("Default timeframe for Technical Analysis")
                ChoiceRow(listOf("15m", "1h", "4h", "1d"), s.defaultTimeframe, { it }, { v -> vm.updateSettings { it.copy(defaultTimeframe = v) } })
                SwitchRow("Include approximate concepts", "Fair Value Gaps, Order Blocks and Elliott wave checks (heuristic approximations).", s.includeApproxConcepts) { v ->
                    vm.updateSettings { it.copy(includeApproxConcepts = v) }
                }
                Muted("Articles per research report")
                ChoiceRow(listOf(10, 15, 20, 30), s.newsCount, { it.toString() }, { v -> vm.updateSettings { it.copy(newsCount = v) } })
            }
        }
        item {
            Panel {
                SectionTitle("Notifications (all optional, off by default)")
                SwitchRow("Significant market movements", "Watchlist coins (or top 10) moving beyond the threshold in 24h.", s.notifyMoves) { v ->
                    if (v) ensurePermission()
                    vm.updateSettings { it.copy(notifyMoves = v) }
                }
                if (s.notifyMoves) {
                    Muted("Threshold: ±${s.moveThresholdPct.toInt()}% in 24h")
                    ChoiceRow(listOf(5f, 8f, 10f, 15f), s.moveThresholdPct, { "${it.toInt()}%" }, { v -> vm.updateSettings { it.copy(moveThresholdPct = v) } })
                }
                SwitchRow("Research report completion", "When an analysis you started finishes.", s.notifyReports) { v ->
                    if (v) ensurePermission()
                    vm.updateSettings { it.copy(notifyReports = v) }
                }
                SwitchRow("Important news updates", "New headlines about regulation, hacks, ETFs and similar topics.", s.notifyNews) { v ->
                    if (v) ensurePermission()
                    vm.updateSettings { it.copy(notifyNews = v) }
                }
                SwitchRow("Data / API errors", "At most once every 6 hours.", s.notifyErrors) { v ->
                    if (v) ensurePermission()
                    vm.updateSettings { it.copy(notifyErrors = v) }
                }
                Muted(
                    if (Scheduler.needed(s)) "Background check scheduled (about every ${maxOf(15, s.refreshMinutes)} min, network + battery constraints)."
                    else "No background activity is scheduled."
                )
            }
        }
        item {
            Panel {
                SectionTitle("Storage management")
                Muted(if (storage.isEmpty()) "Calculating…" else storage)
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    OutlinedButton(onClick = { vm.clearCache(); vm.refreshStorageInfo() }, modifier = Modifier.weight(1f)) { Text("Clear cached data") }
                    OutlinedButton(onClick = { vm.deleteAllReports(); vm.refreshStorageInfo() }, modifier = Modifier.weight(1f)) { Text("Delete all reports") }
                }
            }
        }
        item {
            Panel(Modifier.clickable { showSources = !showSources }) {
                SectionTitle("Data sources & limitations " + if (showSources) "▲" else "▼")
                if (showSources) Text(SOURCES, style = MaterialTheme.typography.bodySmall)
            }
        }
        item {
            Panel(Modifier.clickable { showPrivacy = !showPrivacy }) {
                SectionTitle("Privacy policy " + if (showPrivacy) "▲" else "▼")
                if (showPrivacy) Text(PRIVACY, style = MaterialTheme.typography.bodySmall)
            }
        }
        item {
            Panel(Modifier.clickable { showAbout = !showAbout }) {
                SectionTitle("About " + if (showAbout) "▲" else "▼")
                if (showAbout) {
                    Text("Crypto Research AI v1.0.0", fontWeight = FontWeight.SemiBold)
                    Text(
                        "A multi-agent cryptocurrency market research app for education. It analyses the top 50 coins with eight specialised on-device research modules (market, technical, volume, news, sentiment, bullish evidence, bearish evidence, risk & final report). " +
                            "It does not provide financial advice, buy/sell signals, entry/exit prices or trade execution, and it cannot connect to exchanges.",
                        style = MaterialTheme.typography.bodySmall
                    )
                }
            }
        }
    }
}
